    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String reply = typeField.getText().trim();

        if (reply.isEmpty()) {
            return;
        }

        if (reply.toLowerCase().contains("exit")) {
            try {
                messageField.append("You: " + reply + "\n");
                messageField.append("Gemini: Goodbye! Chat session ended.\n\n");

                typeField.setText("");
                typeField.setEnabled(false);
                jButton1.setEnabled(false);

            } catch (Exception e) {
                System.out.println("Error during exit: " + e.getMessage());
            }
        } else {
            try {
                // Tampilkan pesan user
                messageField.append("You: " + reply + "\n");

                // Disable input sementara
                typeField.setEnabled(false);
                jButton1.setEnabled(false);
                jButton1.setText("Thinking...");

                // Check if Gemini service available
                if (geminiService == null) {
                    messageField.append("Gemini: Sorry, Gemini service is not available. Please check configuration.\n\n");
                    return;
                }

                // Generate response dari Gemini (di background thread)
                new Thread(() -> {
                    try {
                        String response = geminiService.generateResponse(reply);

                        // Update UI di EDT
                        javax.swing.SwingUtilities.invokeLater(() -> {
                            messageField.append("Gemini: " + response + "\n\n");
                            messageField.setCaretPosition(messageField.getDocument().getLength());
                            typeField.setText("");
                        });

                    } catch (Exception e) {
                        javax.swing.SwingUtilities.invokeLater(() -> {
                            messageField.append("Gemini: Sorry, an error occurred: " + e.getMessage() + "\n\n");
                            messageField.setCaretPosition(messageField.getDocument().getLength());
                        });
                        System.out.println("Error: " + e.getMessage());
                    } finally {
                        // Re-enable input
                        javax.swing.SwingUtilities.invokeLater(() -> {
                            typeField.setEnabled(true);
                            jButton1.setEnabled(true);
                            jButton1.setText("Send");
                            typeField.requestFocus();
                        });
                    }
                }).start();

            } catch (Exception e) {
                messageField.append("Gemini: Sorry, an error occurred: " + e.getMessage() + "\n\n");
                System.out.println("Error: " + e.getMessage());

                // Re-enable input
                typeField.setEnabled(true);
                jButton1.setEnabled(true);
                jButton1.setText("Send");
                typeField.requestFocus();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

