    // Optional: Method untuk test Gemini service
    private void testGeminiServiceActionPerformed(java.awt.event.ActionEvent evt) {
        if (geminiService != null) {
            new Thread(() -> {
                try {
                    messageField.append("System: Testing Gemini connection...\n");

                    if (geminiService.testGeminiConnection()) {
                        messageField.append("System: ✅ Gemini connection successful!\n\n");
                    } else {
                        messageField.append("System: ❌ Gemini connection failed!\n\n");
                    }

                    messageField.setCaretPosition(messageField.getDocument().getLength());

                } catch (Exception e) {
                    messageField.append("System: ❌ Test error: " + e.getMessage() + "\n\n");
                    messageField.setCaretPosition(messageField.getDocument().getLength());
                }
            }).start();
        } else {
            messageField.append("System: ❌ Gemini service not initialized!\n\n");
        }
    }

    // Cleanup saat form ditutup
    @Override
    public void dispose() {
        if (geminiService != null) {
            geminiService.close();
        }
        super.dispose();
    }

    // Optional: Method untuk reload konfigurasi Gemini
    private void reloadGeminiConfigActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            if (geminiService != null) {
                geminiService.reloadConfiguration();
                messageField.append("System: ✅ Gemini configuration reloaded\n\n");
            } else {
                // Coba initialize ulang
                geminiService = new bridging.GeminiService();
                messageField.append("System: ✅ Gemini service reinitialized\n\n");
            }
            messageField.setCaretPosition(messageField.getDocument().getLength());

        } catch (Exception e) {
            messageField.append("System: ❌ Failed to reload Gemini config: " + e.getMessage() + "\n\n");
            messageField.setCaretPosition(messageField.getDocument().getLength());
        }
    }

