SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ==================== DDL ==================================

CREATE TABLE IF NOT EXISTS mst_sdki_kategori (
    id          INT NOT NULL,
    kode        VARCHAR(10),
    nama        VARCHAR(50),
    subkategori VARCHAR(100),
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_sdki (
    id          INT NOT NULL,
    kode        VARCHAR(10),
    label       VARCHAR(255),
    definisi    TEXT,
    jenis       VARCHAR(20),
    id_kategori INT,
    aktif       TINYINT(1) DEFAULT 1,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_sdki_tanda_gejala (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    id_sdki   INT NOT NULL,
    tipe      VARCHAR(10),
    kelompok  VARCHAR(20),
    deskripsi TEXT,
    urutan    INT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_sdki_etiologi (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    id_sdki   INT NOT NULL,
    deskripsi TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_slki (
    id       INT NOT NULL,
    kode     VARCHAR(10),
    label    VARCHAR(255),
    definisi TEXT,
    aktif    TINYINT(1) DEFAULT 1,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_slki_indikator (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    id_slki      INT NOT NULL,
    label        VARCHAR(255),
    tipe_skala   VARCHAR(20),
    keterangan_1 VARCHAR(100),
    keterangan_5 VARCHAR(100),
    urutan       INT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_siki (
    id       INT NOT NULL,
    kode     VARCHAR(10),
    label    VARCHAR(255),
    definisi TEXT,
    tipe     VARCHAR(20),
    aktif    TINYINT(1) DEFAULT 1,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mst_siki_tindakan (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    id_siki   INT NOT NULL,
    komponen  VARCHAR(20),
    deskripsi TEXT,
    urutan    INT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS map_sdki_slki (
    id_sdki   INT NOT NULL,
    id_slki   INT NOT NULL,
    prioritas INT DEFAULT 1,
    PRIMARY KEY (id_sdki, id_slki)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS map_sdki_siki (
    id_sdki INT NOT NULL,
    id_siki INT NOT NULL,
    tipe    VARCHAR(20),
    PRIMARY KEY (id_sdki, id_siki)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_header (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    no_rawat    VARCHAR(30),
    no_rm       VARCHAR(20),
    id_perawat  VARCHAR(20),
    nm_perawat  VARCHAR(100),
    tgl_askep   DATE,
    catatan     TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_diagnosis (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    id_header   INT,
    id_sdki     INT,
    kode_sdki   VARCHAR(20),
    label_sdki  VARCHAR(200),
    etiologi    TEXT,
    tanda_mayor TEXT,
    tanda_minor TEXT,
    tgl_diagnosa DATE,
    urutan      INT DEFAULT 0,
    status      VARCHAR(30) DEFAULT 'Aktif'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_luaran (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    id_diagnosis     INT,
    id_slki          INT,
    label_slki       VARCHAR(200),
    skala_awal       INT,
    skala_target     INT,
    waktu_target_hari INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_luaran_indikator (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    id_luaran       INT,
    id_indikator    INT,
    label_indikator TEXT,
    skala_awal      INT,
    skala_target    INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_intervensi (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    id_diagnosis    INT,
    id_siki         INT,
    label_siki      VARCHAR(200),
    tindakan_dipilih TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_evaluasi (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    id_diagnosis  INT,
    tgl_evaluasi  DATE,
    shift         VARCHAR(20),
    soap_s        TEXT,
    soap_o        TEXT,
    soap_a        TEXT,
    soap_p        TEXT,
    kesimpulan    VARCHAR(50),
    id_perawat    VARCHAR(20),
    nm_perawat    VARCHAR(100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS askep_evaluasi_indikator (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    id_evaluasi     INT,
    label_indikator TEXT,
    skala_awal      INT,
    skala_target    INT,
    skala_saat_ini  INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

