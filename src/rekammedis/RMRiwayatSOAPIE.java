    private void BtnPrintActionPerformed(java.awt.event.ActionEvent evt) {
        this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        if(NoRawat.getText().trim().equals("")){
            JOptionPane.showMessageDialog(null,"Maaf, silahkan pilih data pasien terlebih dahulu...!!!!");
        }else{
            try {
                java.io.File g = new java.io.File("file.css");
                java.io.BufferedWriter bg = new java.io.BufferedWriter(new java.io.FileWriter(g));
                bg.write(".tbl_header td{font-family: Tahoma;font-size: 11px;}.tbl_content th{font-family: Tahoma;font-size: 11px;}.tbl_content td{font-family: Tahoma;font-size: 11px;}");
                bg.close();
                
                String noRawat = NoRawat.getText().trim();
                String tglReg = "";
                try {
                     tglReg = new java.text.SimpleDateFormat("yyyyMMdd").format(new java.util.Date());
                } catch(Exception ex) {}

                String finalFileName = "RiwayatSOAPIE_" + noRawat.replaceAll("/", "") + "_" + tglReg;
                String pdfFileName = finalFileName + ".pdf";

                PdfWriter pdf = new PdfWriter(pdfFileName);
                HtmlConverter.convertToPdf(
                        LoadHTML.getText().replaceAll("<head>", "<head><link href=\"file.css\" rel=\"stylesheet\" type=\"text/css\" />").
                                replaceAll("<body>",
                                        "<body>"
                                        + "<table width='100%' align='center' border='0' class='tbl_form' cellspacing='0' cellpadding='0'>"
                                        + "<tr>"
                                        + "<td width='15%' border='0'>"
                                        + "<img width='50' height='50' src='data:image/jpeg;base64," + Base64.getEncoder().encodeToString(Sequel.cariGambar("select setting.logo from setting").readAllBytes()) + "'/>"
                                        + "</td>"
                                        + "<td width='85%' border='0'>"
                                        + "<center>"
                                        + "<font color='000000' size='3'  face='Tahoma'>" + akses.getnamars() + "</font><br>"
                                        + "<font color='000000' size='1'  face='Tahoma'>"
                                        + akses.getalamatrs() + ", " + akses.getkabupatenrs() + ", " + akses.getpropinsirs() + "<br/>"
                                        + akses.getkontakrs() + ", E-mail : " + akses.getemailrs()
                                        + "<br>RIWAYAT SOAPIE"
                                        + "</font> "
                                        + "</center>"
                                        + "</td>"
                                        + "</tr>"
                                        + "</table><br>"
                                ), pdf
                );

                File f = new File(pdfFileName);
                
                if(f.exists()) {
                    try {
                         String kodeBerkas = "RSOAPIE";
                         if(Sequel.cariInteger("select count(kode) from master_berkas_digital where kode='" + kodeBerkas + "'")==0){
                              Sequel.menyimpan("master_berkas_digital", "'" + kodeBerkas + "','Riwayat SOAPIE'", "Kategori Riwayat SOAPIE");
                         }

                         byte[] data = FileUtils.readFileToByteArray(f);
                         HttpClient httpClient = new DefaultHttpClient();
                         HttpPost postReq = new HttpPost("http://" + koneksiDB.HOSTHYBRIDWEB() + ":" + koneksiDB.PORTWEB() + "/" + koneksiDB.HYBRIDWEB() + "/unggah.php?doc=berkasrawat/pages/upload/");
                         postReq.addHeader("X-Upload-Token", fungsi.koneksiDB.TOKENUNGGAH());
                         MultipartEntity reqEntity = new MultipartEntity();
                         reqEntity.addPart("file", new ByteArrayBody(data, f.getName()));
                         postReq.setEntity(reqEntity);
                         httpClient.execute(postReq);

                         String lokasiFile = "pages/upload/" + f.getName();
                         if(Sequel.cariInteger("SELECT COUNT(*) FROM berkas_digital_perawatan WHERE lokasi_file='" + lokasiFile + "'") > 0) {
                              Sequel.mengedittf("berkas_digital_perawatan", "lokasi_file=?", "no_rawat=?,kode=?,lokasi_file=?,nip=?", 5, 
                                 new String[]{noRawat, kodeBerkas, lokasiFile, "-", lokasiFile});
                         } else {
                              Sequel.menyimpantf("berkas_digital_perawatan", "?,?,?,?", "Upload Riwayat SOAPIE", 4, 
                                 new String[]{noRawat, kodeBerkas, lokasiFile, "-"}); 
                         }
                         
                         javax.swing.JOptionPane.showMessageDialog(null, "Berhasil upload ke Berkas Digital", "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    } catch (Exception e) {
                         System.out.println("Upload Error: " + e);
                    }
                }
                Desktop.getDesktop().browse(f.toURI());
            } catch (Exception e) {
                System.out.println("Notifikasi : " + e);
            }
        }
        this.setCursor(Cursor.getDefaultCursor());
    }

