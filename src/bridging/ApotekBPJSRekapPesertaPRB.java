    private void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            try {
                headers = new HttpHeaders();
                headers.setContentType(MediaType.APPLICATION_JSON);
                headers.add("x-cons-id", koneksiDB.CONSIDAPIAPOTEKBPJS());
                utc = String.valueOf(api.GetUTCdatetimeAsString());
                headers.add("x-timestamp", utc);
                headers.add("x-signature", api.getHmac(utc));
                headers.add("user_key", koneksiDB.USERKEYAPIAPOTEKBPJS());
                requestEntity = new HttpEntity(headers);
                URL = link + "/Prb/rekappeserta/tahun/" + cmbTahun.getSelectedItem() + "/bulan/"
                        + String.format("%02d", cmbBulan.getSelectedIndex() + 1);
                root = mapper
                        .readTree(api.getRest().exchange(URL, HttpMethod.GET, requestEntity, String.class).getBody());
                nameNode = root.path("metaData");
                System.out.println("URL : " + URL);
                System.out.println("JSON : " + nameNode);
                System.out.println("Response : " + root);
                if (nameNode.path("code").asText().equals("200")) {
                    response = mapper.readTree(api.Decrypt(root.path("response").asText(), utc));
                    if (response.path("list").isArray()) {
                        for (JsonNode list : response.path("list")) {
                            tabMode.addRow(new Object[] {
                                    list.path("No").asText(),
                                    list.path("NamaPeserta").asText(),
                                    list.path("NomorKaPst").asText(),
                                    list.path("Alamat").asText(),
                                    list.path("TglSRB").asText(),
                                    list.path("Diagnosa").asText(),
                                    list.path("Obat").asText(),
                                    list.path("DPJP").asText(),
                                    list.path("AsalFaskes").asText(),
                            });
                        }
                    }
                }
            } catch (Exception ex) {
                System.out.println("Notifikasi : " + ex);
                if (ex.toString().contains("UnknownHostException")) {
                    JOptionPane.showMessageDialog(rootPane, "Koneksi ke server BPJS terputus...!");
                } else {
                    JOptionPane.showMessageDialog(null, ex.getMessage());
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }

        LCount.setText("" + tabMode.getRowCount());
    }

    private void initTahun() {
        int startYear = 2022;
        int currentYear = LocalDate.now().getYear(); // Mendapatkan tahun sekarang

        for (int year = currentYear; year >= startYear; year--) {
            cmbTahun.addItem(year);
        }
        cmbTahun.setSelectedIndex(0);

        for (String month : bulan) {
            cmbBulan.addItem(month);
        }
        cmbBulan.setSelectedIndex(LocalDate.now().getMonthValue() - 1);
    }
