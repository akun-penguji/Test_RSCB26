    private String getKptlUrl() {
        try {
            String fhir = koneksiDB.URLFHIRSATUSEHAT();
            if (fhir != null && fhir.contains("-stg.")) {
                return KPTL_URL_STG;
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
        return KPTL_URL_PROD;
    }

    private void cariBaseCode() {
        String query = TCari.getText() == null ? "" : TCari.getText().trim();
        if (query.equals("")) {
            JOptionPane.showMessageDialog(this, "Notif : Isi keyword pencarian terlebih dahulu.");
            TCari.requestFocus();
            return;
        }
        Valid.tabelKosong(tabMode);
        Valid.tabelKosong(tabKombinasi);
        try {
            HttpHeaders h = new HttpHeaders();
            h.setContentType(MediaType.APPLICATION_JSON);
            h.add("Authorization", "Bearer " + api.TokenSatuSehat());
            h.add("X-Encryption-Disabled", "true");
            String body = "{\"method\":\"get_all_base_code\",\"query_string\":\""
                    + query.replace("\\", "\\\\").replace("\"", "\\\"")
                    + "\",\"offset\":0,\"limit\":50}";
            HttpEntity<String> req = new HttpEntity<>(body, h);
            String resp = api.getRest().exchange(getKptlUrl() + "/base_code",
                    HttpMethod.POST, req, String.class).getBody();
            JsonNode root = mapper.readTree(resp);
            JsonNode results = root.path("results");
            if (results.isArray() && results.size() > 0) {
                for (JsonNode r : results) {
                    tabMode.addRow(new Object[]{
                        r.path("code").asText(),
                        r.path("display").asText()
                    });
                }
            } else {
                JOptionPane.showMessageDialog(this, "Tidak ada hasil ditemukan untuk : " + query);
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
            JOptionPane.showMessageDialog(this, "Notif : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }

    private void cariKombinasi(String baseCode) {
        if (baseCode == null || baseCode.trim().equals("")) return;
        Valid.tabelKosong(tabKombinasi);
        try {
            HttpHeaders h = new HttpHeaders();
            h.setContentType(MediaType.APPLICATION_JSON);
            h.add("Authorization", "Bearer " + api.TokenSatuSehat());
            h.add("X-Encryption-Disabled", "true");
            String body = "{\"method\":\"get_modifiers\",\"query_string\":\""
                    + baseCode.replace("\\", "\\\\").replace("\"", "\\\"")
                    + "\",\"max_iteration\":2}";
            HttpEntity<String> req = new HttpEntity<>(body, h);
            String resp = api.getRest().exchange(getKptlUrl() + "/base_code_combination",
                    HttpMethod.POST, req, String.class).getBody();
            JsonNode root = mapper.readTree(resp);
            JsonNode finals = root.path("final_codes");
            if (finals.isArray()) {
                for (JsonNode f : finals) {
                    String fullCode, fullDisp;
                    if (f.isTextual()) {
                        fullCode = f.asText();
                        fullDisp = "";
                    } else {
                        fullCode = f.path("code").asText();
                        if (fullCode == null || fullCode.equals("")) {
                            fullCode = f.path("final_code").asText();
                        }
                        fullDisp = f.path("display").asText();
                        if (fullDisp == null || fullDisp.equals("")) {
                            fullDisp = f.path("final_display").asText();
                        }
                    }
                    tabKombinasi.addRow(new Object[]{fullCode, fullDisp});
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
    }
