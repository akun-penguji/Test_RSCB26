    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {
        if(TxtNoRawat.getText().trim().equals("")){
            Valid.textKosong(TxtNoRawat,"No.Rawat");
        }else if(TxtNIKPasien.getText().trim().equals("")){
            Valid.textKosong(TxtNIKPasien,"NIK Pasien");
        }else if(TxtNamaPasien.getText().trim().equals("")){
            Valid.textKosong(TxtNamaPasien,"Nama Pasien");
        }else{
            this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            try {
                // Buat dialog konfirmasi custom dengan opsi notifikasi
                DialogKonfirmasiKirim dialogKonfirmasi = new DialogKonfirmasiKirim(this, true);
                dialogKonfirmasi.setVisible(true);
                
                int pilihanKirim = dialogKonfirmasi.getPilihanKirim();
                boolean tampilkanNotif = dialogKonfirmasi.isTampilkanNotifikasi();
                
                String statusLaporan = "Menunggu Proses";
                String responseAPI = "";
                
                // Jika user pilih kirim otomatis
                if(pilihanKirim == JOptionPane.YES_OPTION) {
                    try {
                        JOptionPane.showMessageDialog(null, "Sedang mengirim laporan ke Satu Sehat...\nMohon tunggu sebentar.", "Mengirim Data", JOptionPane.INFORMATION_MESSAGE);
                        
                        // Kirim ke API Satu Sehat
                        ApiSatuSehat apiSatuSehat = new ApiSatuSehat();
                        responseAPI = apiSatuSehat.kirimLaporanNIK(
                            TxtNoRawat.getText(),
                            TxtNIKPasien.getText(),
                            TxtNamaPasien.getText(),
                            TxtNIKPraktisi.getText(),
                            TxtNamaPraktisi.getText(),
                            cmbJenisLaporan.getSelectedItem().toString(),
                            TxtKeterangan.getText()
                        );
                        
                        if(responseAPI != null && !responseAPI.startsWith("ERROR")) {
                            statusLaporan = "Terkirim ke Satu Sehat";
                            if(tampilkanNotif) {
                                JOptionPane.showMessageDialog(null, 
                                    "✅ Laporan berhasil dikirim ke Satu Sehat!\n\n" +
                                    "Response: " + responseAPI.substring(0, Math.min(responseAPI.length(), 200)) +
                                    (responseAPI.length() > 200 ? "..." : ""),
                                    "Berhasil Terkirim", 
                                    JOptionPane.INFORMATION_MESSAGE);
                            }
                        } else {
                            statusLaporan = "Gagal Kirim - " + (responseAPI != null ? responseAPI.substring(6, Math.min(responseAPI.length(), 50)) : "Unknown error");
                            if(tampilkanNotif) {
                                JOptionPane.showMessageDialog(null, 
                                    "⚠️ Gagal mengirim ke Satu Sehat!\n\n" +
                                    "Error: " + responseAPI + "\n\n" +
                                    "Data tetap disimpan di database lokal.\n" +
                                    "Anda dapat mengirim manual melalui portal resmi.",
                                    "Gagal Kirim", 
                                    JOptionPane.WARNING_MESSAGE);
                            }
                        }
                    } catch (Exception e) {
                        statusLaporan = "Error API - " + e.getMessage();
                        if(tampilkanNotif) {
                            JOptionPane.showMessageDialog(null, 
                                "❌ Terjadi error saat mengirim ke Satu Sehat!\n\n" +
                                "Error: " + e.getMessage() + "\n\n" +
                                "Data tetap disimpan di database lokal.\n" +
                                "Anda dapat mengirim manual melalui portal resmi.",
                                "Error API", 
                                JOptionPane.ERROR_MESSAGE);
                        }
                    }
                }
                
                // Simpan ke database lokal untuk tracking
                if(Sequel.menyimpantf("laporan_nik_satusehat","?,?,?,?,?,?,?,?,?,?","Data",10,new String[]{
                    new SimpleDateFormat("yyyy-MM-dd").format(new Date()),
                    new SimpleDateFormat("HH:mm:ss").format(new Date()),
                    TxtNoRawat.getText(),
                    TxtNIKPasien.getText(),
                    TxtNamaPasien.getText(),
                    TxtNIKPraktisi.getText(),
                    TxtNamaPraktisi.getText(),
                    cmbJenisLaporan.getSelectedItem().toString(),
                    TxtKeterangan.getText(),
                    statusLaporan
                })==true){
                    JOptionPane.showMessageDialog(null,"Data laporan berhasil disimpan di database lokal!");
                    
                    // Generate laporan untuk dikirim
                    generateLaporanFile();
                    
                    // Reset form
                    emptTeks();
                    
                    // Refresh riwayat
                    tampilRiwayat();
                    
                    // Tanyakan apakah ingin buka portal (hanya jika tidak kirim otomatis)
                    if(pilihanKirim == JOptionPane.NO_OPTION) {
                        int pilihanPortal = JOptionPane.showConfirmDialog(null, 
                            "Laporan berhasil disimpan!\n\n" +
                            "Apakah Anda ingin membuka portal pelaporan NIK Satu Sehat untuk kirim manual?", 
                            "Buka Portal", 
                            JOptionPane.YES_NO_OPTION);
                        
                        if(pilihanPortal == JOptionPane.YES_OPTION){
                            BtnBrowserActionPerformed(evt);
                        }
                    }
                }
            } catch (Exception e) {
                System.out.println("Notifikasi : "+e);
            }
            this.setCursor(Cursor.getDefaultCursor());
        }
    }

