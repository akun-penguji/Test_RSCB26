    private void tampilRiwayat() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement(
                "SELECT tanggal, jam, no_rawat, nik_pasien, nama_pasien, " +
                "jenis_laporan, status, keterangan " +
                "FROM laporan_nik_satusehat " +
                "ORDER BY tanggal DESC, jam DESC LIMIT 100");
            rs = ps.executeQuery();
            while(rs.next()){
                tabMode.addRow(new Object[]{
                    rs.getString("tanggal") + " " + rs.getString("jam"),
                    rs.getString("no_rawat"),
                    rs.getString("nik_pasien"),
                    rs.getString("nama_pasien"),
                    rs.getString("jenis_laporan"),
                    rs.getString("status"),
                    rs.getString("keterangan")
                });
            }
        } catch (Exception e) {
            System.out.println("Error tampil riwayat: " + e);
        } finally {
            if(rs != null) {
                try { rs.close(); } catch (Exception e) {}
            }
            if(ps != null) {
                try { ps.close(); } catch (Exception e) {}
            }
        }
    }
    
