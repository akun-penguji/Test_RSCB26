    private void BtnCsvActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCsvActionPerformed
        if(tabMode.getRowCount()==0){
            JOptionPane.showMessageDialog(null,"Maaf, data masih kosong. Tidak ada yang bisa diexport...!!!");
            return;
        }
        JFileChooser fc=new JFileChooser();
        fc.setDialogTitle("Simpan CSV");
        fc.setSelectedFile(new File("LamaWaktuPelayananMobileJKN.csv"));
        if(fc.showSaveDialog(this)==JFileChooser.APPROVE_OPTION){
            File file=fc.getSelectedFile();
            if(!file.getName().toLowerCase().endsWith(".csv")){
                file=new File(file.getParentFile(),file.getName()+".csv");
            }
            try(FileWriter fw=new FileWriter(file)){
                int kolom=tabMode.getColumnCount();
                StringBuilder sb=new StringBuilder();
                for(int c=0;c<kolom;c++){
                    if(c>0) sb.append(",");
                    sb.append(csv(tabMode.getColumnName(c)));
                }
                sb.append("\r\n");
                for(int r=0;r<tabMode.getRowCount();r++){
                    for(int c=0;c<kolom;c++){
                        if(c>0) sb.append(",");
                        Object v=tabMode.getValueAt(r,c);
                        sb.append(csv(v==null?"":v.toString()));
                    }
                    sb.append("\r\n");
                }
                fw.write(sb.toString());
                fw.flush();
                JOptionPane.showMessageDialog(null,"Berhasil export "+tabMode.getRowCount()+" baris ke:\n"+file.getAbsolutePath());
            }catch(Exception e){
                JOptionPane.showMessageDialog(null,"Gagal export CSV : "+e);
            }
        }
}//GEN-LAST:event_BtnCsvActionPerformed

