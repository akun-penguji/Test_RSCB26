    /**
     * Tampil data dari database master_komposisi
     * Membuat cache file untuk performa yang lebih baik
     */
    private void tampil() {
        Valid.tabelKosong(tabMode);
        try{  
            file=new File("./cache/master_komposisi.iyem");
            file.createNewFile();
            fileWriter = new FileWriter(file);
            iyem="";
            
            // Query dari master_komposisi dengan status aktif
            ps=koneksi.prepareStatement(
                "SELECT kode_komposisi, nama_standar, nama_generik, kategori, " +
                "kekuatan_umum, satuan, variasi_nama " +
                "FROM master_komposisi " +
                "WHERE status_aktif = '1' " +
                "ORDER BY nama_standar ASC"
            );
            
            try {
                rs=ps.executeQuery();
                while(rs.next()){
                    tabMode.addRow(new String[]{
                        rs.getString("kode_komposisi"),
                        rs.getString("nama_standar"),
                        rs.getString("nama_generik") != null ? rs.getString("nama_generik") : "",
                        rs.getString("kategori") != null ? rs.getString("kategori") : "",
                        rs.getString("kekuatan_umum") != null ? rs.getString("kekuatan_umum") : "",
                        rs.getString("satuan") != null ? rs.getString("satuan") : ""
                    });
                    
                    // Build JSON untuk cache - Escape quotes properly
                    String namaStandar = rs.getString("nama_standar").replace("\"", "\\\"");
                    String namaGenerik = rs.getString("nama_generik") != null ? rs.getString("nama_generik").replace("\"", "\\\"") : "";
                    String kategori = rs.getString("kategori") != null ? rs.getString("kategori").replace("\"", "\\\"") : "";
                    String kekuatan = rs.getString("kekuatan_umum") != null ? rs.getString("kekuatan_umum").replace("\"", "\\\"") : "";
                    String satuan = rs.getString("satuan") != null ? rs.getString("satuan").replace("\"", "\\\"") : "";
                    String variasi = rs.getString("variasi_nama") != null ? rs.getString("variasi_nama").replace("\"", "\\\"") : "";
                    
                    iyem += "{" +
                        "\"KodeKomposisi\":\"" + rs.getString("kode_komposisi") + "\"," +
                        "\"NamaStandar\":\"" + namaStandar + "\"," +
                        "\"NamaGenerik\":\"" + namaGenerik + "\"," +
                        "\"Kategori\":\"" + kategori + "\"," +
                        "\"Kekuatan\":\"" + kekuatan + "\"," +
                        "\"Satuan\":\"" + satuan + "\"," +
                        "\"VariasiNama\":\"" + variasi + "\"" +
                        "},";
                }
            } catch (Exception e) {
                System.out.println("Error query: " + e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            }   
            
            if(iyem.length() > 0) {
                fileWriter.write("{\"master_komposisi\":["+iyem.substring(0,iyem.length()-1)+"]}");
            } else {
                fileWriter.write("{\"master_komposisi\":[]}");
            }
            fileWriter.flush();
            fileWriter.close();
            iyem=null;
        }catch(Exception e){
            System.out.println("Notifikasi tampil: "+e);
        }
        LCount.setText(""+tabMode.getRowCount());
    }
    
    /**
     * Tampil data dari cache file dengan filter pencarian
     * Mendukung pencarian di nama standar, nama generik, dan variasi nama
     */
    private void tampil2() {
        try {
            // Cek apakah file cache ada
            file = new File("./cache/master_komposisi.iyem");
            if(!file.exists()) {
                // Jika tidak ada cache, buat dulu
                tampil();
                return;
            }
            
            myObj = new FileReader("./cache/master_komposisi.iyem");
            root = mapper.readTree(myObj);
            Valid.tabelKosong(tabMode);
            response = root.path("master_komposisi");
            
            if(response.isArray()){
                String cariText = TCari.getText().toLowerCase().trim();
                
                for(JsonNode list:response){
                    boolean found = false;
                    
                    // Jika pencarian kosong, tampilkan semua
                    if(cariText.isEmpty()) {
                        found = true;
                    } else {
                        // Cari di nama standar
                        if(list.path("NamaStandar").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di nama generik
                        else if(list.path("NamaGenerik").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di kategori
                        else if(list.path("Kategori").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di kode komposisi
                        else if(list.path("KodeKomposisi").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di variasi nama
                        else if(list.path("VariasiNama").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di kekuatan
                        else if(list.path("Kekuatan").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                        // Cari di satuan
                        else if(list.path("Satuan").asText().toLowerCase().contains(cariText)){
                            found = true;
                        }
                    }
                    
                    if(found) {
                        tabMode.addRow(new Object[]{
                            list.path("KodeKomposisi").asText(),
                            list.path("NamaStandar").asText(),
                            list.path("NamaGenerik").asText(),
                            list.path("Kategori").asText(),
                            list.path("Kekuatan").asText(),
                            list.path("Satuan").asText()
                        });
                    }
                }
            }
            myObj.close();
        } catch (Exception ex) {
            System.out.println("Notifikasi tampil2: "+ex);
            // Jika gagal baca cache, tampil langsung dari database
            System.out.println("Cache error, falling back to database...");
            tampilFromDatabase();
        }
        LCount.setText(""+tabMode.getRowCount());
    }
    
    /**
     * Fallback method untuk tampil langsung dari database saat pencarian
     */
    private void tampilFromDatabase() {
        Valid.tabelKosong(tabMode);
        try{    
            ps=koneksi.prepareStatement(
                "SELECT kode_komposisi, nama_standar, nama_generik, kategori, " +
                "kekuatan_umum, satuan " +
                "FROM master_komposisi " +
                "WHERE status_aktif = '1' AND (" +
                "kode_komposisi LIKE ? OR nama_standar LIKE ? OR " +
                "nama_generik LIKE ? OR kategori LIKE ? OR " +
                "kekuatan_umum LIKE ? OR satuan LIKE ? OR " +
                "variasi_nama LIKE ?) " +
                "ORDER BY nama_standar ASC"
            );
            
            try {
                String cari = "%"+TCari.getText().trim()+"%";
                ps.setString(1, cari);
                ps.setString(2, cari);
                ps.setString(3, cari);
                ps.setString(4, cari);
                ps.setString(5, cari);
                ps.setString(6, cari);
                ps.setString(7, cari);
                rs=ps.executeQuery();
                while(rs.next()){
                    tabMode.addRow(new String[]{
                        rs.getString("kode_komposisi"),
                        rs.getString("nama_standar"),
                        rs.getString("nama_generik") != null ? rs.getString("nama_generik") : "",
                        rs.getString("kategori") != null ? rs.getString("kategori") : "",
                        rs.getString("kekuatan_umum") != null ? rs.getString("kekuatan_umum") : "",
                        rs.getString("satuan") != null ? rs.getString("satuan") : ""
                    });
                }
            } catch (Exception e) {
                System.out.println("Error query fallback: " + e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            }            
        }catch(Exception e){
            System.out.println("Error tampilFromDatabase: "+e);
        }
    }

